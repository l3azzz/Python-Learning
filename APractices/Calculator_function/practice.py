def calculator(first,second,operation):
    if operation == "/":
        print( first / second)
    elif operation == "*":
        print( first * second)
    elif operation == "-":
        print( first - second)
    elif operation == "+":
        print( first + second)
    elif operation == "%":
        print( first % second)
    else:
        pass
        


calculator(20,5,"+")